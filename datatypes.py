# Different data types in Python
name = "Ravi"            # String
age = 22                  # Integer
height = 5.9              # Float
is_student = True         # Boolean
hobbies = ["reading", "music"]   # List
coordinates = (12, 15)    # Tuple
profile = {               # Dictionary
    "city": "Hyderabad",
    "country": "India"
}

# Printing the type of each variable
print("Name type:", type(name))
print("Age type:", type(age))
print("Height type:", type(height))
print("is_student type:", type(is_student))
print("Hobbies type:", type(hobbies))
print("Coordinates type:", type(coordinates))
print("Profile type:", type(profile))

# Printing the actual values
print("Name:", name)
print("Age:", age)
print("Height:", height)
print("Is student:", is_student)
print("Hobbies:", hobbies)
print("Coordinates:", coordinates)
print("Profile:", profile)
