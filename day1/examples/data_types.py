"""
Python Primitive Data Types Examples
"""


def display_basic_data_types() -> None:
    employee_name = "Karthik"
    employee_age = 21
    employee_salary = 50000.50
    is_active = True

    print(f"Name     : {employee_name}")
    print(f"Age      : {employee_age}")
    print(f"Salary   : {employee_salary}")
    print(f"Active   : {is_active}")


if __name__ == "__main__":
    display_basic_data_types()