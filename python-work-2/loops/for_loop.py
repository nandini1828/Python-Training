"""
For Loop examples.
"""


def iterate_list():

    fruits = ["Apple", "Orange", "Banana"]

    for fruit in fruits:
        print(fruit)


def iterate_string():

    for ch in "Python":
        print(ch)


def iterate_range():

    for i in range(5):
        print(i)


def demo():

    iterate_list()

    iterate_string()

    iterate_range()